class EvenOrOdd 
{
	public static void main(String args[]){

        	int no1 = Integer.parseInt(args[0]);

        	if(no1 % 2 == 0)
	{
            		System.out.println("the number is a even" + no1);
       	 }
        	else
	{
            		System.out.println("the number is a odd: " + no1);
        }
    }
}